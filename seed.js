export function seedIfEmpty() {
  const d = db.data;
  if (d.books.length === 0) {
    for (const b of BOOKS) {
      d.books.push({ id: db.id(), audience: 'adult', ...b });
    }
    for (const b of CLASSROOM) {
      d.books.push({ id: db.id(), audience: 'youth', mode: 'light', minutes: 10, alsoFor: [], situations: [], portion: '', curatorNote: '', question: '', ...b });
    }
  }
  if (d.challenges.length === 0) {
    for (const c of CHALLENGES) {
      d.challenges.push({ id: db.id(), ...c, createdAt: Date.now() });
    }
  }
  db.save(true);
}
